export function draftPath(registrationId, suffix = '') {
  const id = encodeURIComponent(registrationId);
  return `/api/registro/drafts/${id}${suffix}`;
}

export function isTerminalDraftStatus(status) {
  return [DRAFT_STATUS.COMPLETED, DRAFT_STATUS.EXPIRED, DRAFT_STATUS.CANCELLED].includes(status);
}
